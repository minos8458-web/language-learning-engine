async function registerReference(prefix, kind, suffix, version, definition) {
  const referenceId = `${prefix}_${suffix}`;
  await repository.registerReferenceVersion(pool, {
    referenceKind: kind,
    referenceId,
    version,
    definition: definition ?? { kind, referenceId, version },
  });
  return referenceId;
}

async function setupAuthorityFixture(prefix) {
  const nodeA = `${prefix}_NODE_A`;
  const nodeB = `${prefix}_NODE_B`;
  await pool.query(
    `INSERT INTO grammar_nodes (node_id, language, concept_ids, label, difficulty)
     VALUES ($1, 'VI', '[]'::jsonb, $2, 1), ($3, 'VI', '[]'::jsonb, $4, 1)`,
    [nodeA, `${prefix} Node A`, nodeB, `${prefix} Node B`]
  );

  const experimentId = `${prefix}_EXP`;
  const conditionId = `${prefix}_COND`;
  await repository.registerExperimentVersion(pool, {
    experimentId,
    version: 1,
    definition: { protocol: 'B3_M1_CALIBRATION' },
  });
  await repository.registerConditionVersion(pool, {
    conditionId,
    version: 1,
    conditionClass: 'ENGINEERING_BASELINE',
    definition: { mode: 'FIXED' },
  });

  const ruleId = `${prefix}_RULE_NO_ERROR`;
  const itemId = await registerReference(prefix, 'ITEM', 'ITEM', 1);
  const scenarioId = await registerReference(prefix, 'SCENARIO', 'SCEN', 1);
  const itemFamilyId = await registerReference(prefix, 'ITEM_FAMILY', 'FAM', 1);
  const lexicalManifestId = await registerReference(prefix, 'LEXICAL_MANIFEST', 'LEX', 1);
  const rubricId = await registerReference(
    prefix,
    'RUBRIC',
    'RUBRIC',
    1,
    rubricDefinition(prefix, nodeA, nodeB)
  );
  const formulaId = await registerReference(prefix, 'FORMULA', 'FORM', 1);
  const schedulerProtocolId = await registerReference(prefix, 'SCHEDULER_PROTOCOL', 'SCHED', 1);
  const instrumentationProtocolId = await registerReference(
    prefix,
    'INSTRUMENTATION_PROTOCOL',
    'INSTR',
    1,
    instrumentationDefinition()
  );

  const participant = await repository.createParticipant(pool, {});
  const enrollment = await repository.createEnrollment(pool, {
    participantId: participant.participant_id,
    experimentId,
    experimentVersion: 1,
    conditionId,
    conditionVersion: 1,
  });

  const references = {
    itemId,
    itemVersion: 1,
    scenarioId,
    scenarioVersion: 1,
    itemFamilyId,
    itemFamilyVersion: 1,
    lexicalManifestId,
    lexicalManifestVersion: 1,
    rubricId,
    rubricVersion: 1,
    formulaId,
    formulaVersion: 1,
    schedulerProtocolId,
    schedulerProtocolVersion: 1,
    instrumentationProtocolId,
    instrumentationProtocolVersion: 1,
  };

  return { enrollment, references, nodeA, nodeB, ruleId };
}

