  // FAMILY 7-FULL generalized scope, explicitly deferred here.
  const { rows: digestRows } = await pool.query(
    `SELECT digest_algorithm, normalization_version, finalization_payload_digest
       FROM evidence_attempt_finalizations WHERE attempt_id = $1`,
    [family2.attemptId]
  );
