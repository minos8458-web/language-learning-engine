async function countRows(queryable, table, whereSql, params) {
  const { rows } = await queryable.query(
    `SELECT count(*) AS n FROM ${table}${whereSql ? ` WHERE ${whereSql}` : ''}`,
    params
  );
  return Number(rows[0].n);
}

