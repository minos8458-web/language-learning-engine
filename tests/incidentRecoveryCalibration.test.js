// FAMILY 1 — transient DB read failure
// ---------------------------------------------------------------------------

async function runFamily1(fixture, prefix) {
  const assignment = await createFixtureAssignment(fixture);
  const assignmentId = assignment.assignment.assignment_id;

  const injectedFaultStartMs = harness.nowMs();
  const injectedFaultStart = harness.isoNow();
  const counter = harness.createFaultCounter(2);
  const faultyPool = harness.wrapPoolWithFaults(pool, {
    matcher: /^SELECT \* FROM evidence_assignments WHERE assignment_id/i,
    counter,
  });

  const { result, trace } = await harness.runWithHarnessRecovery({
    operation: () => repository.getAssignmentAggregate(faultyPool, assignmentId),
    maxAttempts: HARNESS_INPUTS.maxAttempts,
    spacingMs: HARNESS_INPUTS.spacingMs,
    cadenceMode: HARNESS_INPUTS.cadenceMode,
  });

  const firstSuccess = trace.find((entry) => entry.recovery_succeeded);
  const healthyAtMs = firstSuccess.recovery_attempt_at_ms;

  const verificationStart = harness.isoNow();
  const verificationStartMs = harness.nowMs();
  const { rows: directRows } = await pool.query(
    'SELECT assignment_id, terminal_outcome FROM evidence_assignments WHERE assignment_id = $1',
    [assignmentId]
  );
  const integrityPass = Boolean(
    result
    && result.assignment
    && directRows[0]
    && result.assignment.assignment_id === directRows[0].assignment_id
    && result.assignment.terminal_outcome === directRows[0].terminal_outcome
  );
  const verificationEnd = harness.isoNow();
  const verificationEndMs = harness.nowMs();

  harness.assertCausalOrder([
    { name: 'injected_fault_start', value: injectedFaultStartMs },
    { name: 'first_recovery_attempt_at', value: trace[0].recovery_attempt_at_ms },
    { name: 'healthy_at', value: healthyAtMs },
    { name: 'integrity_verification_start_at', value: verificationStartMs },
    { name: 'integrity_verified_at', value: verificationEndMs },
  ]);

  return buildEpisode({
    failure_family: 'FAMILY_1_TRANSIENT_READ',
    affected_scope: 'evidence_assignments read via getAssignmentAggregate',
    attempt_id: null,
    session_id: null,
    assignment_id: assignmentId,
    fault_duration_ms: 0,
    healthy_at: new Date(healthyAtMs).toISOString(),
    retry_attempt_spacing_ms: HARNESS_INPUTS.spacingMs,
    recovery_attempt_ordinal: trace.length,
    recovery_attempt_at: trace.map((e) => e.recovery_attempt_at),
    recovery_succeeded: true,
    error_class: trace[0].error_class,
    recovery_detection_latency_ms: healthyAtMs - injectedFaultStartMs,
    integrity_verification_latency_ms: verificationEndMs - verificationStartMs,
    integrity_verification_result: integrityPass ? 'PASS' : 'FAIL',
    duplicate_detected: false,
    contamination_detected: false,
    missing_ambiguity_detected: false,
    diagnostic: {
      retry_cadence_mode: HARNESS_INPUTS.cadenceMode,
      fault_recoverability_state_by_attempt: trace.map((e) => e.fault_recoverability_state),
      injected_fault_start: injectedFaultStart,
      first_recovery_attempt_at: trace[0].recovery_attempt_at,
      integrity_verification_start_at: verificationStart,
      integrity_verified_at: verificationEnd,
      fixture_scale: FIXTURE_SCALE,
      integrity_check_set: ['recomputed_read_matches_direct_read'],
      total_recovery_elapsed_ms: verificationEndMs - injectedFaultStartMs,
      fault_counter_observations: counter.attempts,
      matrix_prefix: prefix,
    },
  });
}

